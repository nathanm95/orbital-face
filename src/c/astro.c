#include "orbital.h"

// -----------------------------------------------------------------------------
// Real heliocentric positions, in integer arithmetic only.
//
// Method: Paul Schlyter's low-precision elements, but solved with the series
// expansion of the equation of centre instead of iterating Kepler numerically.
// That trades a fraction of a degree of accuracy for having no floating point,
// no atan2, no fmod and no unbounded loop anywhere on the path — which is what
// makes it safe to call from window_load on a 2KB stack.
//
// Accuracy against a full Kepler solve is better than 0.1 deg for every planet
// except Mercury (~0.02 deg with the e^3 term kept). A planet dot is 3px wide
// on a 180px screen, so one pixel is about 2 degrees of arc. This is far past
// what the display can show.
// -----------------------------------------------------------------------------

typedef struct {
  uint16_t m0;         // mean anomaly at epoch, trig units
  int32_t  mrate_q16;  // mean motion, trig units per day, Q16
  uint16_t peri;       // longitude of perihelion, trig units
  int16_t  c1, c2, c3; // equation-of-centre coefficients, trig units
  uint16_t ecc_q16;    // eccentricity, Q16
} OrbitElements;

// GENERATED by tools/gen_elements.py -- do not hand-edit the numbers.
// Epoch d=0 is 1999-12-31.0 UT. Angles in Pebble trig units (65536 = full turn).
static const OrbitElements ELEMENTS[PLANET_COUNT] = {
  { /* Mercury */ 30703,   48823452, 14100,  4290,  551,  98, 13476 },
  { /* Venus   */  8739,   19114158, 23952,   141,    1,   0,   444 },
  { /* Earth   */ 64816,   11758669, 18740,   349,    4,   0,  1095 },
  { /* Mars    */  3386,    6251811, 61178,  1948,  114,   9,  6121 },
  { /* Jupiter */  3622,     991246,  2609,  1012,   31,   1,  3178 },
  { /* Saturn  */ 57702,     399005, 16941,  1159,   40,   2,  3640 },
  { /* Uranus  */ 25958,     139894, 31068,   987,   29,   1,  3101 },
  { /* Neptune */ 47377,      71525,  8124,   180,    1,   0,   564 },
};

// Days since the epoch, Q16. Kept in a 64-bit intermediate because seconds
// since 1970 times 65536 overflows int32 comfortably.
static int32_t day_number_q16(time_t utc) {
  // 1999-12-31.0 UT == unix 946598400
  int64_t secs = (int64_t)utc - 946598400LL;
  return (int32_t)((secs * 65536LL) / 86400LL);
}

void astro_positions(time_t utc, PlanetPos out[PLANET_COUNT]) {
  const int32_t d_q16 = day_number_q16(utc);

  for (int i = 0; i < PLANET_COUNT; i++) {
    const OrbitElements *e = &ELEMENTS[i];

    // Mean anomaly. mrate_q16 * d_q16 is a Q32 product, so shift 32 back down.
    int64_t travelled = (int64_t)e->mrate_q16 * (int64_t)d_q16;
    int32_t M = (int32_t)(e->m0 + (int32_t)(travelled >> 32));
    M &= 0xFFFF;

    // True anomaly via the equation of centre:
    //   v = M + 2e.sinM + 1.25e^2.sin2M + (13/12)e^3.sin3M
    int32_t s1 = sin_lookup(M);
    int32_t s2 = sin_lookup((M * 2) & 0xFFFF);
    int32_t s3 = sin_lookup((M * 3) & 0xFFFF);
    int32_t v = M
              + (e->c1 * s1 / TRIG_MAX_RATIO)
              + (e->c2 * s2 / TRIG_MAX_RATIO)
              + (e->c3 * s3 / TRIG_MAX_RATIO);

    out[i].longitude = (v + e->peri) & 0xFFFF;

    // Radius as a fraction of the mean: r/a ~= 1 - e.cos(M).
    // Q16 throughout so the caller can scale a pixel radius by it directly.
    int32_t cosM = cos_lookup(M);
    out[i].r_q16 = 65536 - (int32_t)(((int64_t)e->ecc_q16 * cosM) / TRIG_MAX_RATIO);
  }
}

// -----------------------------------------------------------------------------
// Moon phase. The synodic month is a steady 29.530588 days and the only thing
// the face needs is the terminator, so the mean phase is plenty — a true
// ephemeris would move the answer by well under half a pixel of shading.
// -----------------------------------------------------------------------------

void astro_moon(time_t utc, int32_t *phase_deg, int *illum_pct) {
  // A known new moon: 2000-01-06 18:14 UT.
  const int64_t known_new = 947182440LL;
  const int64_t synodic   = 2551443LL;       // 29.530588 days in seconds

  int64_t age = ((int64_t)utc - known_new) % synodic;
  if (age < 0) age += synodic;

  int32_t deg = (int32_t)((age * 360LL) / synodic);
  if (phase_deg) *phase_deg = deg;

  if (illum_pct) {
    // illumination = (1 - cos(phase)) / 2
    int32_t c = cos_lookup((deg * 65536 / 360) & 0xFFFF);
    *illum_pct = (int)((TRIG_MAX_RATIO - c) * 100 / (2 * TRIG_MAX_RATIO));
  }
}

// Orbit shape, for drawing the path. Perihelion longitude and eccentricity are
// what the renderer needs to offset the orbit circle toward aphelion.
void astro_orbit_shape(int i, int32_t *peri, int32_t *ecc_q16) {
  if (i < 0 || i >= PLANET_COUNT) { *peri = 0; *ecc_q16 = 0; return; }
  *peri    = ELEMENTS[i].peri;
  *ecc_q16 = ELEMENTS[i].ecc_q16;
}
